"""BOOT SMILE -- at power-on a white pixel face on black (spiral eyes, crooked grin) grows from the centre, stays, then melts away.

Replaces the Elektron logo's drawing inside the stock boot animation (the LED wave stays) and
lengthens the animation from 2.8 s to 3.8 s. Frames generated by tools/bootsmile/gen_bootsmile.py.

Sites, measured from the user's 1.40C (24 Oct 2026; base 0x40000400; modules/bootsmile/bootsmile.s):
  * 0x400559b6: the operand of `lea 0x400128a8,%fp` in the boot logo FUN_4005596c, the blit both
    of its draws go through, and nothing else in that routine -> bs_blit.
  * 0x40055b76: the operand of `cmpi.l #559,%d0`, the loop's end in 5 ms units -> 760.
"""

import os

from remix.schema import Category, Gate, Kind, Linked, Module, Poke, Proof, SymbolRef

H = bytes.fromhex
_HERE = os.path.relpath(os.path.dirname(os.path.realpath(__file__)))

MODULE = Module(
    name="bootsmile",
    key="BOOT_SMILE",
    kind=Kind.CF_PATCH,
    category=Category.UTILITIES,
    author="MaMarko",
    author_url="https://github.com/braikomarko-hub",
    doc=("At power-on a white pixel face on black (spiral eyes, crooked grin) grows from the centre, stays a moment, then melts off the "
         "screen, in place of the Elektron logo (the LED wave stays). 3.8 s instead of 2.8 s."),
    proof=Proof.CHECK,
    proof_note="tools/bootsmile/test_bootsmile.py (the source under cfsim); not yet on the unit",
    linked=(
        Linked("bootsmile", os.path.join(_HERE, "bootsmile.s"), dram=True),
    ),
    symbol_refs=(
        SymbolRef(0x400559B6, 0x400128A8, "bootsmile", "bs_blit",
                  "boot logo FUN_4005596c: its blit (%fp) -> the smile's frame for the logo, nothing for the stars"),
    ),
    pokes=(
        Poke(0x40055B76, H("0000022f"), H("000002f8"),
             "boot logo loop end: 559 -> 760 units of 5 ms (2.8 s -> 3.8 s), the smile's length"),
    ),
    gates=(
        Gate("tools/bootsmile/test_bootsmile.py", remix_arg=False),
    ),
)
