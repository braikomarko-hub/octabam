#!/usr/bin/env python3
"""Build the ColdFire unit `trackpatterns.s` from trackpattern.c + adapter.c
+ hooks.s, or --check that the checked-in copy is current, or --dry to
compile only. The algorithm stays in C; the builder links GNU-as.

Needs m68k-elf-gcc (Homebrew's bottle or the SDK toolchain). Reads no
firmware.
"""
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
FLAGS = ['-mcpu=5475', '-msoft-float', '-O2', '-ffreestanding', '-fno-builtin', '-fno-common',
         '-fno-tree-loop-distribute-patterns', '-fno-jump-tables', '-fno-asynchronous-unwind-tables',
         '-fno-ident', '-fomit-frame-pointer', '-std=c11', '-Wall', '-Wextra', '-Werror']
SOURCES = ('trackpattern.c', 'adapter.c')
# Stock targets the unit may reach besides its own labels: the places the
# detour stubs jump back to (hooks.s, manifest.py), the two stock calls of
# the key stub (the toast 0x4005a2b8, the rebuild 0x4009da20) and the two of
# the LED stub (running? 0x4009b290, the UI step 0x4009b2b0). Anything
# else (a libgcc helper, a memset the optimiser invented, a mistyped
# address) fails.
STOCK_CALLS = {'0x400a2d7c', '0x400a39c6', '0x4009dc94', '0x4009e3ea', '0x400a3d8e', '0x400a3eae',
               '0x40056b56', '0x40056ba4', '0x4005a2b8', '0x4009da20', '0x4007e9bc',
               '0x4009b290', '0x4009b2b0'}


def compiler():
    gcc = shutil.which('m68k-elf-gcc')
    if not gcc:
        sys.exit('m68k-elf-gcc not found (brew install m68k-elf-gcc, or the SDK toolchain)')
    return gcc


def generate():
    gcc = compiler()
    parts = ['| Generated by generate.py from trackpattern.c, adapter.c and hooks.s.\n'
             '| Edit those; run `python3 generate.py` to refresh this file.\n']
    # One translation unit, so GCC's local labels (.L3 ...) never collide.
    with tempfile.TemporaryDirectory() as td:
        unit = pathlib.Path(td) / 'trackpatterns_unit.c'
        unit.write_text(''.join(f'#include "{HERE / name}"\n' for name in SOURCES))
        out = pathlib.Path(td) / 'unit.s'
        subprocess.run([gcc, *FLAGS, '-I', str(HERE), '-S', unit.name, '-o', str(out)], cwd=td, check=True)
        parts.append('| ---- trackpattern.c + adapter.c ----\n' + out.read_text())
    parts.append('| ---- hooks.s ----\n' + (HERE / 'hooks.s').read_text())
    return '\n'.join(parts)


def external_calls(source):
    calls = set()
    for line in source.splitlines():
        words = line.split()
        if len(words) >= 2 and words[0] in ('jsr', 'jbsr', 'bsr', 'jmp', 'jra', 'bsr.l'):
            target = words[1].split(',')[0].lstrip('(').rstrip(')')
            if not target.startswith(('.', '%')):
                calls.add(target)
    defined = {m.group(1) for m in re.finditer(r'^([A-Za-z_.$][\w.$]*):', source, re.M)}
    return calls - defined - STOCK_CALLS


def assemble(source):
    """Assemble the whole unit for the 5475, so a stub the ColdFire cannot
    encode fails here and not in the firmware build."""
    with tempfile.TemporaryDirectory() as td:
        src = pathlib.Path(td) / 'trackpatterns.s'
        src.write_text(source)
        result = subprocess.run([compiler(), '-mcpu=5475', '-c', '-x', 'assembler', str(src),
                                 '-o', str(pathlib.Path(td) / 'trackpatterns.o')], capture_output=True, text=True)
        if result.returncode:
            sys.exit('trackpatterns.s does not assemble for the 5475:\n' + result.stderr)


if __name__ == '__main__':
    source = generate()
    stray = external_calls(source)
    if stray:
        sys.exit(f'trackpatterns.s calls outside the unit: {sorted(stray)}')
    assemble(source)
    dest = HERE / 'trackpatterns.s'
    if '--dry' in sys.argv:
        print(f'ColdFire compile and assembly OK ({len(source.splitlines())} lines), no calls outside the unit')
    elif '--check' in sys.argv:
        if not dest.exists() or dest.read_text() != source:
            sys.exit('trackpatterns.s is stale: run python3 generate.py')
        print('trackpatterns.s matches trackpattern.c, adapter.c and hooks.s')
    else:
        dest.write_text(source)
        print(f'wrote {dest.name} ({len(source.splitlines())} lines): assembles for the 5475, no library calls')
