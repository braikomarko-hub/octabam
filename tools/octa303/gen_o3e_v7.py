#!/usr/bin/env python3
"""OCTA303 vFable - the v7 engine's generated block (code written by Claude, Anthropic).

modules/octa303/octa303.s carries, between its "o3e generated" markers, the data of the v7 voice:
  * the integer control step's tables, as model_v7/gen_tables.py emits them from the knob laws
    (tools/octa303/leggi_A_v5.json), turned into this file's form (.align 4 + label + .long / .short in the text);
  * the scalars of model_v7/o3tab.h (O3S_*) as .set constants, and a few derived ones (O3E_*): the per-sample
    constants the model computes from the laws in C doubles (computed here with the same double expressions), the
    poles' u offsets, the ACCV split, the C3 increment (C3 = 130.8128 Hz);
  * the BA662A ceiling's two knee tables (model_v7 o3model.KNEG / KPOS).

  python3 tools/octa303/gen_o3e_v7.py            print the block
  python3 tools/octa303/gen_o3e_v7.py --write    replace the block in modules/octa303/octa303.s
  python3 tools/octa303/gen_o3e_v7.py --check    exit 1 if the block in octa303.s is not this one

The reference model lives outside the repository (it is the designer's): O3_MODEL_V7=DIR names it (default
../../vfable/model_v7 beside the repository's parent).  The tables are generated by running its gen_tables.py.
"""
import os, sys, re, math, subprocess, tempfile, importlib.util

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
SRC = os.path.join(ROOT, 'modules', 'octa303', 'octa303.s')
LAWS = os.path.join(HERE, 'leggi_A_v5.json')
MODEL = os.environ.get('O3_MODEL_V7') or os.path.normpath(os.path.join(ROOT, '..', '..', 'vfable', 'model_v7'))
BEGIN = '| ---- o3e generated: tools/octa303/gen_o3e_v7.py (do not edit by hand)'
END = '| ---- o3e generated: end'
FS = 44100.0
C3_HZ = 130.8128                     # TUNE 0 = C3, standard tuning (A4 = 440 Hz): the shell's owners, 13 Nov 2026


def s32(v):
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v & 0x80000000 else v


def q31(x):                          # o3k.c q31(): floor, capped at 0.99999999 and -1
    if x > 0.99999999: x = 0.99999999
    if x < -1.0: x = -1.0
    return int(math.floor(x * 2147483648.0))


def load_model():
    if not os.path.isfile(os.path.join(MODEL, 'o3model.py')):
        sys.exit('gen_o3e_v7: the model is not at %s (set O3_MODEL_V7)' % MODEL)
    spec = importlib.util.spec_from_file_location('o3model_v7', os.path.join(MODEL, 'o3model.py'))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m


def gen_tables():
    """run the model's gen_tables.py on the laws; -> (o3tab.s lines, {O3S_name: value})"""
    with tempfile.TemporaryDirectory() as td:
        subprocess.check_call([sys.executable, os.path.join(MODEL, 'gen_tables.py'), LAWS, td], stdout=subprocess.DEVNULL)
        s = open(os.path.join(td, 'o3tab.s')).read().split('\n')
        h = open(os.path.join(td, 'o3tab.h')).read()
    sc = {k: int(v) for k, v in re.findall(r'#define (O3S_\w+) \((-?\d+)\)', h)}
    return s, sc


def block():
    m = load_model()
    M = m.load_laws(LAWS)
    tab, sc = gen_tables()
    out = [BEGIN,
           '| From the laws tools/octa303/leggi_A_v5.json through model_v7 (gen_tables.py, o3model.py); code written by',
           '| Claude (Anthropic).  Layout and Q formats: model_v7 o3int.h.']
    for k, v in sc.items():
        out.append('        .set    %s, %d' % (k, v))
    # per-sample constants: o3k.c core() computes them in doubles from the parameter vector
    GhD = math.pi * M['fh'] / FS; GhD = GhD / (1.0 + GhD)
    der = dict(O3E_GH=q31(GhD), O3E_DUTY=int(math.floor(M['duty'] * 4294967296.0)) & 0xFFFFFFFF,
               O3E_LEAK=q31(M['leak']), O3E_SQLEV=q31(M['sqlev']))
    assert M['sawdir'] > 0, 'the engine has the rising saw only (sawdir 1)'
    for j in range(4):                                   # u = octd + LR_j - U0, as one add (mod 2^32 the same)
        der['O3E_LRU%d' % j] = s32(sc['O3S_LR%d' % j] - sc['O3S_U0'])
    der['O3E_ACCVH'] = sc['O3S_ACCV'] >> 6               # (ACCV * k) >> 6 = (ACCV >> 6) k + (((ACCV & 63) k) >> 6)
    der['O3E_ACCVL'] = sc['O3S_ACCV'] & 63
    der['O3E_INCC3'] = int(math.floor(C3_HZ / FS * 4294967296.0))
    der['O3E_O2MAX'] = int(17.9 * 16777216)              # o3int.h TRCK: (int32_t)(17.9 * 16777216)
    assert 2 * (der['O3E_INCC3'] << 3) < (1 << 30), 'inc0 << 1 must stay below 2^31 at +3 octaves'
    for k, v in der.items():
        out.append('        .set    %s, %s' % (k, ('0x%08x' % v) if k == 'O3E_DUTY' else str(v)))
    # the tables: drop the section directives, every table on a 4-byte boundary
    for line in tab:
        t = line.strip()
        if not t or t.startswith('|') or t in ('.data', '.even'):
            continue
        if t.endswith(':'):
            out.append('        .align  4'); out.append(t)
        else:
            out.append('        ' + t)
    for name, T in (('o3e_kneg', m.KNEG), ('o3e_kpos', m.KPOS)):
        out.append('        .align  4'); out.append(name + ':')
        for i in range(0, len(T), 8):
            out.append('        .long   ' + ', '.join(str(int(v)) for v in T[i:i + 8]))
    out.append(END)
    return '\n'.join(out) + '\n', m.tables_bytes()


def splice(src, blk):
    i = src.index('| ---- o3e generated:'); j = src.index(END, i) + len(END) + 1
    return src[:i] + blk + src[j:]


if __name__ == '__main__':
    blk, nb = block()
    if '--write' in sys.argv or '--check' in sys.argv:
        src = open(SRC).read(); new = splice(src, blk)
        if '--check' in sys.argv:
            ok = new == src
            print('gen_o3e_v7 --check: %s (%d table bytes)' % ('the block is current' if ok else 'THE BLOCK DIFFERS', nb))
            sys.exit(0 if ok else 1)
        open(SRC, 'w').write(new); print('wrote the block into %s (%d table bytes + the knee tables)' % (SRC, nb))
    else:
        sys.stdout.write(blk)
