"""Generates o3c.asm: OCTA303's smooth chain on the DSP56300, from u (after the oscillator, the input highpass and
OVDR's gain) to the output word, integer-exact against ref303 (coordination, 19 Nov 2026; code written by Claude).

Every ref303 fm(d, c, pre, post) = floor(floor(d / 2^pre) * c / 2^post) is done as:
  d in an accumulator (56-bit, exact) ; asr #pre ; A = a1 ; mpy A,c (the 48-bit product = 2*A*c, exact) ;
  asl #(23 - post) ; a1 = the result (a0 keeps the dropped fraction: a1 is the floor).
That is exact while A, c < 2^23 and the result < 2^23 (checked on the stress run, split303/stress.py).

ABI (bench and glue): r0 = the piece's samples, two words each: X:(r0) = u's low 24 bits, X:(r0+1) = u's high byte (a2); the output
word v (the s16 value, unshifted) is written over X:(r0); the ladder's four states are 32-bit (a1 + a2), so u and the
ladder keep ref303's range with OVDR up to 127 (u to 6.2 x 2^23, y1 to 1.6 x 2^23, measured by the review);
r6 = the piece's control block, r7 = the voice's state block, n7 = the piece's length (1..16).
Uses a, b, x0, x1, y0, y1, r1, r2, n1.  No rep (the norep rule)."""
import sys
import os; sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
import o3tables as T

FTAB, FPTAB = 0x800, 0x910          # Y: pin 6's tables (P6_F, P6_FP), 258 words each
def neg24(v): return (1 << 24) - v
# state X:(r7+n)
S_FB, S_Y1, S_Y2, S_Y3, S_Y4, S_VP1, S_VP2, S_DC, S_AMP, S_FBV, S_Y0V, S_OV, S_Y1H, S_Y2H, S_Y3H, S_Y4H = range(16)
HI = {1: 12, 2: 13, 3: 14, 4: 15}
# control X:(r6+n)
P_C1, P_B, P_K, P_CLG, P_CLI, P_CLL, P_W2, P_GC, P_AMP0, P_STEP = range(10)

L = []
def e(s): L.append('        ' + s)
def lab(s): L.append(s + ':')
def fm_tail(acc, pre, coef_load, post, d_reg='y0', c_reg='x0'):
    """acc holds d (exact).  Leaves the result in acc1 (acc0 = the fraction)."""
    e('asr     #%d,%s,%s' % (pre, acc, acc)) if pre else None
    e('move    %s1,%s' % (acc, d_reg))
    e(coef_load)
    e('mpy     %s,%s,%s' % (d_reg, c_reg, acc))
    s = 23 - post
    e(('asl     #%d,%s,%s' % (s, acc, acc)) if s > 0 else ('asr     #%d,%s,%s' % (-s, acc, acc)))

def ld(acc, st):
    e('move    x:(r7+%d),%s' % (st, acc))
    e('move    x:(r7+%d),%s2' % (HI[st], acc))
def sto(acc, st):
    e('move    %s1,x:(r7+%d)' % (acc, st))
    e('move    %s2,x:(r7+%d)' % (acc, HI[st]))
L.append('; o3c -- generated by gen_o3c.py: OCTA303 smooth chain, integer-exact (see the generator)')
lab('o3c_run')
e('move    #>$ffffff,m1')                          # r1, r2 walk linearly (the caller's m1..m5 are not ours)
e('move    #>$ffffff,m2')
e('move    x:(r6+%d),x0' % P_AMP0)
e('move    x0,x:(r7+%d)' % S_AMP)
e('do      n7,o3c_end')
# ---- the loop highpass: fbst += fm(y4 - fbst, FBHP, 4, 11); fb = clamp(y4 - fbst)
ld('a', S_Y4)
e('move    x:(r7+%d),x0' % S_FB)
e('sub     x0,a')
fm_tail('a', 4, 'move    #>%d,x0' % T.TB_FBHP, 11)
e('move    a1,x0')
e('move    x:(r7+%d),b' % S_FB)
e('add     x0,b')
e('move    b,x:(r7+%d)' % S_FB)
ld('a', S_Y4)
e('sub     b,a')
e('move    a,x1')                                   # limiting move: the clamp (+2^23 lands on 2^23 - 1)
e('move    x1,x:(r7+%d)' % S_FBV)
# ---- kx = (fb >> 8) * k ; lin = u - kx
e('move    x1,a')
fm_tail('a', 8, 'move    x:(r6+%d),x0' % P_K, 0)
e('move    x:(r0),b')
e('move    x:(r0+1),b2')
e('sub     a,b')                                    # a0 = 0 here (2*A*k shifted by 23)
# ---- the ladder's clip
e('move    x:(r6+%d),a' % P_CLG)
e('tst     a')
e('jne     o3c_clg')
e('jsr     o3c_sclip')
e('jmp     o3c_lad')
lab('o3c_clg')
e('move    x:(r6+%d),x0' % P_CLL)
e('cmp     x0,b')
e('tgt     x0,b')
e('move    x0,a')
e('neg     a')
e('move    a1,x0')
e('cmp     x0,b')
e('tlt     x0,b')
fm_tail('b', 4, 'move    x:(r6+%d),x0' % P_CLG, 8)
e('move    b1,x0')
e('move    x0,b')
e('jsr     o3c_sclip')
fm_tail('b', 4, 'move    x:(r6+%d),x0' % P_CLI, 8)
e('move    b1,x0')
e('move    x0,b')
lab('o3c_lad')
e('move    b1,x:(r7+%d)' % S_Y0V)
# ---- the ladder, 32-bit states in accumulators: y1 += fm(y0 - y1 + y2, c1, 7, 8), then y2, y3, y4 with b
def lad(first, mid, nxt, coef, st):
    """a = d; asr #7; mpy; asl #15; a0 cleared (the floor, exact); + the old state"""
    fm_tail('a', 7, 'move    x:(r6+%d),x0' % coef, 8)
    e('move    #0,a0')
    ld('b', st)
    e('add     b,a')
    sto('a', st)
e('move    x:(r7+%d),a' % S_Y0V)
ld('b', S_Y1)
e('sub     b,a')
ld('b', S_Y2)
e('add     b,a')
lad(None, None, None, P_C1, S_Y1)
ld('b', S_Y2)                                       # a = new y1
e('sub     b,a')
e('sub     b,a')
ld('b', S_Y3)
e('add     b,a')
lad(None, None, None, P_B, S_Y2)
ld('b', S_Y3)                                       # a = new y2
e('sub     b,a')
e('sub     b,a')
ld('b', S_Y4)
e('add     b,a')
lad(None, None, None, P_B, S_Y3)
ld('b', S_Y4)                                       # a = new y3
e('sub     b,a')
e('sub     b,a')
lad(None, None, None, P_B, S_Y4)
# ---- the VCA's input pair
def hp(state, coef):
    e('move    x:(r7+%d),a' % S_FBV)
    e('move    x:(r7+%d),x1' % state)
    e('sub     x1,a')
    fm_tail('a', 4, 'move    #>%d,x0' % coef, 11)
    e('move    a1,x0')
    e('move    x1,a')
    e('add     x0,a')
    e('move    a,x:(r7+%d)' % state)
hp(S_VP1, T.VP_HP1)
e('move    a1,x0')
e('move    x:(r7+%d),b' % S_FBV)
e('sub     x0,b')                                   # b = fb - vp1
hp(S_VP2, T.VP_HP2)
e('move    a1,x0')
e('move    x:(r7+%d),a' % S_FBV)
e('sub     x0,a')                                   # a = fb - vp2
fm_tail('a', 6, 'move    x:(r6+%d),x0' % P_W2, 6)
e('move    a1,x0')
e('add     x0,b')                                   # b = x
# ---- level: o = fm(x, gcomp, 6, 6); clamp OTA_LIM; the OTA; clamp VCA_LIM
fm_tail('b', 6, 'move    x:(r6+%d),x0' % P_GC, 6)
# no clean-up here: o can pass 2^23 (stress: 8,877,810); the clamp below compares all 56 bits, and b0 (the
# dropped fraction, 0 <= f < 1) changes neither the clamp nor the floor of the next shift
e('move    #>%d,x0' % T.OTA_LIM)
e('cmp     x0,b')
e('tgt     x0,b')
e('move    #>%d,x0' % neg24(T.OTA_LIM))
e('cmp     x0,b')
e('tlt     x0,b')
fm_tail('b', 4, 'move    #>%d,x0' % T.OTA_IN, 8)
e('move    b1,x0')
e('move    x0,b')
e('jsr     o3c_sclip')
fm_tail('b', 4, 'move    #>%d,x0' % T.OTA_OUT, 11)
e('move    b1,x0')
e('move    x0,b')
e('move    #>%d,x0' % T.VCA_LIM)
e('cmp     x0,b')
e('tgt     x0,b')
e('move    #>%d,x0' % neg24(T.VCA_LIM))
e('cmp     x0,b')
e('tlt     x0,b')
# ---- the VCA: amp = max(0, amp + step); o = fm(o, amp >> 1, 7, 6)
e('move    x:(r7+%d),a' % S_AMP)
e('move    x:(r6+%d),x0' % P_STEP)
e('add     x0,a')
e('move    #0,x1')
e('tst     a')
e('tlt     x1,a')
e('move    a1,x:(r7+%d)' % S_AMP)
e('asr     #1,a,a')
e('move    a1,x0')
e('asr     #7,b,b')
e('move    b1,y0')
e('mpy     y0,x0,b')
e('asl     #17,b,b')
e('move    b,x0')                                   # limiting: past 2^23 the pin-6 table is flat anyway (|o| >= 1.9M)
e('move    x0,b')
e('move    x0,x:(r7+%d)' % S_OV)
# ---- pin 6: o -> sign(o) * F(64 |o| / L), linear between 257 points
e('tst     b')
e('jlt     o3c_p6n')
e('move    #>%d,y1' % T.P6_KP)
e('move    #%d,r1' % FPTAB)
e('jmp     o3c_p6k')
lab('o3c_p6n')
e('move    #>%d,y1' % T.P6_K)
e('move    #%d,r1' % FTAB)
lab('o3c_p6k')
e('abs     b')                                      # |o| < 2^23 <= P6_AMAX: the table's clamp never acts here
e('asr     #6,b,b')
e('move    b1,x1')
e('mpy     y1,x1,b')                                # 2 * (|o| >> 6) * K
e('asl     #5,b,b')                                 # b1 = i = floor(AK / 2^18), b0 = the rest << 5
e('move    b0,x0')
e('move    x0,a')
e('lsr     #9,a')                                   # a1 = (t & 0xFFFF) >> 1
e('move    a1,y0')
e('move    #>256,x0')
e('cmp     x0,b')
e('jge     o3c_p6f')
e('move    b1,n1')
e('lua     (r1)+n1,r2')
e('move    y:(r2)+,x0')
e('move    y:(r2),a')
e('sub     x0,a')
e('move    a1,x1')
e('mpy     x1,y0,a')
e('asl     #8,a,a')
e('move    a1,x1')
e('move    x0,a')
e('add     x1,a')
e('jmp     o3c_p6s')
lab('o3c_p6f')
e('move    y:(r1+256),a')
lab('o3c_p6s')
e('move    a1,x1')
e('neg     a')
e('move    x:(r7+%d),b' % S_OV)
e('tst     b')
e('tge     x1,a')                                   # o >= 0: +v
# ---- output coupling: dc += fm(o - dc, DCHP, 4, 11); v = clamp((o - dc) >> SHIFT_OUT, +-32767)
e('move    a1,x1')
e('move    x:(r7+%d),x0' % S_DC)
e('sub     x0,a')
fm_tail('a', 4, 'move    #>%d,x0' % T.TB_DCHP, 11)
e('move    a1,x0')
e('move    x:(r7+%d),a' % S_DC)
e('add     x0,a')
e('move    a,x:(r7+%d)' % S_DC)
e('move    a1,x0')
e('move    x1,b')
e('sub     x0,b')
e('asr     #%d,b,b' % T.SHIFT_OUT)
e('move    #>32767,x0')
e('cmp     x0,b')
e('tgt     x0,b')
e('move    #>%d,x0' % neg24(32767))
e('cmp     x0,b')
e('tlt     x0,b')
e('move    b1,x:(r0)+')
e('move    (r0)+')
lab('o3c_end')
e('rts')
# ---- softclip: b -> clamp(b, +-1482910); b - ((((b>>8)^2 >> 12) * (b>>8) >> 12) * 10923 >> 8)
lab('o3c_sclip')
e('move    #>1482910,x0')
e('cmp     x0,b')
e('tgt     x0,b')
e('move    #>%d,x0' % neg24(1482910))
e('cmp     x0,b')
e('tlt     x0,b')
e('move    b1,x0')
e('move    x0,a')
e('asr     #8,a,a')
e('move    a1,x0')
e('mpy     x0,x0,a')
e('asl     #11,a,a')
e('move    a1,y0')
e('mpy     y0,x0,a')
e('asl     #11,a,a')
e('move    a1,y0')
e('move    #>10923,x0')
e('mpy     y0,x0,a')
e('asl     #15,a,a')
e('move    a1,x0')
e('sub     x0,b')
e('rts')
open(sys.argv[1] if len(sys.argv) > 1 else 'o3c.asm', 'w').write('\n'.join(L) + '\n')
