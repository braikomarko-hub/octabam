"""OCTA303 vFable model v7 - emit the integer control step's tables (code written by Claude).

python3 gen_tables.py [laws.json] [outdir]
From the knob laws (default leggi_A_v5.json) builds the same tables as o3model.int_tables() (the model renders with
those) and writes:
  o3tab.h  a C header: one const array per table (int32_t, or int16_t for the tables shipped as int16) and the scalars;
  o3tab.s  the same data as assembler text (.long / .short, one label per table) for the ColdFire build.
Prints the size of each table and the total.
"""
import os, sys, json
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import o3model as m


def main():
    a = [x for x in sys.argv[1:]]
    laws = a[0] if a else os.path.join(HERE, 'leggi_A_v5.json')
    out = a[1] if len(a) > 1 else HERE
    M = m.load_laws(laws)
    blob, T, sc = m.int_tables(M, parts=True)
    h = ['/* OCTA303 vFable - integer control step tables (generated by gen_tables.py from %s; code written by Claude).' % os.path.basename(laws),
         ' * Layout and Q formats: o3int.h.  Do not edit. */', '#include <stdint.h>']
    s = ['| OCTA303 vFable - integer control step tables (generated by gen_tables.py from %s; code written by Claude)' % os.path.basename(laws),
         '| Layout and Q formats: o3int.h.  Do not edit.', '        .data', '        .even']
    rows = []; total = 0
    for nm, n in m.TB_LAYOUT:
        v = np.asarray(T[nm], np.int64).reshape(-1)
        if nm == 'SC':
            for k, x in zip(m.SC_NAMES, v): h.append('#define O3S_%s (%d)' % (k, int(x)))
        w16 = nm in m.TB16; ty = 'int16_t' if w16 else 'int32_t'; size = n * (2 if w16 else 4); total += size
        rows.append((nm, n, ty, size))
        h.append('static const %s O3T_%s[%d] = {' % (ty, nm, n))
        for i in range(0, n, 8): h.append('    ' + ', '.join(str(int(x)) for x in v[i:i + 8]) + ',')
        h.append('};')
        s.append('O3T_%s:' % nm)
        for i in range(0, n, 8): s.append('        %s %s' % ('.short' if w16 else '.long', ', '.join(str(int(x)) for x in v[i:i + 8])))
    h.append('#define O3_TABLES_BYTES %d' % total)
    open(os.path.join(out, 'o3tab.h'), 'w').write('\n'.join(h) + '\n')
    open(os.path.join(out, 'o3tab.s'), 'w').write('\n'.join(s) + '\n')
    for nm, n, ty, size in rows: print('%-6s %4d x %-7s %5d bytes' % (nm, n, ty, size))
    print('total %d bytes (%.2f KB); the model blob checks: %d entries, o3int.h TB_N = %d' % (total, total / 1024, len(blob), m._lib.o3_tab_n()))
    assert total == m.tables_bytes()


if __name__ == '__main__':
    main()
