"""STROJ -- modello di riferimento v1 (30 ott 2026): uguale, numero per numero, a stroj.s.

Differenze dalla v0 (stroj_model.py), tutte per poter essere copiate uguali dal ColdFire:
  * l'incremento di fase di una nota viene da una tabella di un'ottava (768 voci) + shift,
    come OCTA303 (inc_of_p), non da 2^x;
  * niente divisioni di numeri negativi (sul ColdFire divs.l tronca, Python arrotonda in giu'):
    /3 della saturazione = *10923 >> 15, il mix delle placche = *MIXG[voic] >> 15;
  * il filtro tiene i suoi stati in +-65535 (cosi' nessun prodotto supera 32 bit);
  * tutte le curve delle manopole sono tabelle (TAB), generate qui e scritte in stroj_tables.inc.

Uso:  render(seconds, knobfn)  come nella v0;  Voice.render(knobs12, n) -> n campioni Q15.
      python3 tools/stroj/stroj_ref.py --write   rigenera modules/stroj/stroj_tables.inc
Manopole (lista di 12 valori 0..127): NOTE SPRD INTV FM SUB TONE / VOIC SUB1 SUB2 BRTH RYTM WAVE
"""
import math

SR, FRAME, M32 = 44100, 16, 0xFFFFFFFF
NAMES = ("NOTE", "SPRD", "INTV", "FM", "SUB", "TONE", "VOIC", "SUB1", "SUB2", "BRTH", "RYTM", "WAVE")
DEFAULT = dict(NOTE=64, SPRD=40, INTV=64, FM=40, SUB=50, TONE=90,
               VOIC=127, SUB1=0, SUB2=20, BRTH=40, RYTM=30, WAVE=0)
INTERVALS = ((0, "UNI"), (3, "MIN3"), (4, "MAJ3"), (5, "4TH"), (7, "5TH"),
             (10, "MIN7"), (12, "OCT"), (19, "OCT5"))
RYTMS = ((0, 0, "OFF"), (3, 4, "3:4"), (4, 5, "4:5"), (3, 5, "3:5"), (5, 7, "5:7"))
WAVES = ("SIN", "TRI", "SAW", "SQR")
NOTE_NAMES = ("C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B")
TBITS = 11


# ---------------------------------------------------------------- le tabelle (costanti)
def _wave(kind):
    t = []
    for i in range(1 << TBITS):
        x = 2 * math.pi * i / (1 << TBITS)
        if kind == "SIN":
            v = math.sin(x)
        else:
            v = 0.0
            for h in range(1, 49):
                if kind == "SAW":
                    v += math.sin(h * x) / h * 0.55
                elif kind == "SQR" and h % 2:
                    v += math.sin(h * x) / h * 0.85
                elif kind == "TRI" and h % 2:
                    v += math.sin(h * x) / (h * h) * (1 if (h // 2) % 2 == 0 else -1) * 0.81
        t.append(max(-32767, min(32767, int(round(v * 32767)))))
    return t

TAB = {
    "WAVE": [v for w in WAVES for v in _wave(w)],                                   # 4 x 2048 .short
    # incremento di fase dell'ottava piu' bassa (MIDI 0..11.99, passi di 1/64 di semitono)
    "INC": [int(440.0 * 2 ** ((r * 4 / 256 - 69) / 12) * (1 << 32) / SR) for r in range(768)],
    "SPRD": [int(round(k * k / 540 * 256 / 100)) for k in range(128)],              # semitoni Q8
    "INTV": [iv << 8 for iv, _ in INTERVALS],
    "FM": [k * k // 4 for k in range(128)],
    "BSTEP": [0] + [max(1, 131072 // int(SR / FRAME * 2 * 32 ** ((k - 1) / 126))) for k in range(1, 128)],
    "TONE": [int(32767 * 2 * math.sin(math.pi * (40 * 2 ** (k / 127 * 7.2)) / SR)) for k in range(128)],
    "MIXG": [0] + [65536 // (v + 2) for v in range(1, 5)],
    "RYA": [a for a, _, _ in RYTMS],
    "RYB": [b for _, b, _ in RYTMS],
}

def write_inc(path):
    """Le tabelle per l'assembly (stroj_tables.inc)."""
    with open(path, "w") as f:
        f.write("| STROJ tables, generated by stroj_ref.py -- do not edit\n")
        for name, kind in (("WAVE", ".short"), ("INC", ".long"), ("SPRD", ".long"), ("INTV", ".long"),
                           ("FM", ".long"), ("BSTEP", ".long"), ("TONE", ".long"), ("MIXG", ".long"),
                           ("RYA", ".long"), ("RYB", ".long")):
            f.write("        .align 4\nsj_t_%s:\n" % name.lower())
            vals = TAB[name]
            for i in range(0, len(vals), 16):
                f.write("        %s %s\n" % (kind, ",".join(str(v) for v in vals[i:i + 16])))


def inc_of(p):                           # p = nota in semitoni Q8 (MIDI * 256), >= 0
    o, r = divmod(p, 3072)
    return (TAB["INC"][r >> 2] << o) & M32

def clamp(x, lo, hi): return lo if x < lo else hi if x > hi else x

def note_name(midi): return f"{NOTE_NAMES[midi % 12]}{midi // 12 - 1}"

def toast(k):
    """Il messaggio che compare girando NOTE o INTV (come 'C4 +OCT' di OCTA303)."""
    base = clamp(k[0] - 28, 12, 84)
    iv, name = INTERVALS[k[2] >> 4]
    return f"{note_name(base)}.{note_name(base + iv)} {name}"


# ---------------------------------------------------------------- la voce
# Stato (come il blocco in memoria di stroj.s, 13 long):
#   ph[4] fasi delle placche, sp[2] fasi delle sotto-ottave, prev[4] ultime uscite, lfo, lo, bp
class Voice:
    def __init__(self):
        self.ph = [0, 0x40000000, 0x15555555, 0x6AAAAAAA]
        self.sp = [0, 0]
        self.prev = [0, 0, 0, 0]
        self.lfo = self.lo = self.bp = 0

    def render(self, k, n=FRAME):
        # ---------------- una volta per chiamata (control rate)
        base = clamp(k[0] - 28, 12, 84) << 8
        iv = TAB["INTV"][k[2] >> 4]
        sp = TAB["SPRD"][k[1]]
        voic = (k[6] >> 5) + 1
        pitch = (base + sp, base - sp, base + iv + sp, base + iv - sp)
        inc = [inc_of(pitch[v]) for v in range(voic)]
        wo = (k[11] >> 5) << TBITS                       # inizio dell'onda nella tabella
        step = TAB["BSTEP"][k[9]]
        if step:
            self.lfo = (self.lfo + step) & 0x1FFFF
            tri = self.lfo if self.lfo < 65536 else 0x1FFFF - self.lfo
            br = tri >> 1
        else:
            br = 16384
        fm = (TAB["FM"][k[3]] * (8192 + ((br * 3) >> 2))) >> 15
        sub = k[4] * 258
        g1 = g2 = sub
        if sub:
            ry = (k[10] * 5) >> 7
            a, b = TAB["RYA"][ry], TAB["RYB"][ry]
            if a and step:
                p1 = (self.lfo * a) & 0x1FFFF
                p2 = (self.lfo * b) & 0x1FFFF
                t1 = (p1 if p1 < 65536 else 0x1FFFF - p1) >> 1
                t2 = (p2 if p2 < 65536 else 0x1FFFF - p2) >> 1
                g1 = (sub * (8192 + ((t1 * 3) >> 2))) >> 15
                g2 = (sub * (8192 + ((t2 * 3) >> 2))) >> 15
            ib = inc_of(base)
            sinc1 = ib // (2 + ((k[7] * 7) >> 7))
            sinc2 = ib // (2 + ((k[8] * 7) >> 7))
        mixg = TAB["MIXG"][voic]
        mixg2 = (mixg * 26214) >> 15
        tone = k[5]
        f = TAB["TONE"][tone]
        W = TAB["WAVE"]
        ph, prev = self.ph, self.prev
        out = []
        # ---------------- per campione
        for _ in range(n):
            acc = acc2 = 0                               # le due coppie, sommate a parte
            for v in range(voic):
                p = ph[v] = (ph[v] + inc[v]) & M32
                if fm:
                    m = prev[v ^ 2] if voic > 2 else prev[v ^ 1]
                    p = (p + ((m * fm) << 4)) & M32
                s = W[wo + (p >> (32 - TBITS))]
                prev[v] = s
                if v < 2: acc += s
                else: acc2 += s
            acc = (acc * mixg + acc2 * mixg2) >> 15         # la 2a coppia a 0.8: dentro il guadagno
            if sub:
                self.sp[0] = (self.sp[0] + sinc1) & M32
                self.sp[1] = (self.sp[1] + sinc2) & M32
                q1 = 16384 if self.sp[0] & 0x80000000 else -16384
                q2 = 16384 if self.sp[1] & 0x80000000 else -16384
                acc += (q1 * g1 + q2 * g2) >> 15             # q*g = +-(g << 14), g<<14 fatto una volta
            x = clamp(acc, -32767, 32767)                # saturazione: 1.5 (x - x^3/3)
            c = (((x * x) >> 15) * x) >> 15
            acc = ((x - ((c * 10923) >> 15)) * 3) >> 1
            if tone < 127:                               # TONE 127 = OFF, il filtro non si calcola
                hi = clamp(acc - self.lo - ((self.bp * 23000) >> 15), -65535, 65535)
                self.bp = clamp(self.bp + ((f * hi) >> 15), -65535, 65535)
                self.lo = clamp(self.lo + ((f * self.bp) >> 15), -65535, 65535)
                acc = self.lo
            out.append(clamp(acc, -32767, 32767))
        return out


def knobs(d):
    kn = dict(DEFAULT); kn.update(d)
    return [kn[n] for n in NAMES]

def render(seconds, knobfn):
    v = Voice(); out = []
    for i in range(int(seconds * SR) // FRAME):
        out += v.render(knobs(knobfn(i * FRAME / SR)))
    return out


TABLES_INC = __import__("os").path.join(__import__("os").path.dirname(__import__("os").path.abspath(__file__)),
                                        "..", "..", "modules", "stroj", "stroj_tables.inc")

if __name__ == "__main__":
    import sys
    if "--write" in sys.argv:
        write_inc(TABLES_INC)
        print("wrote", TABLES_INC)
